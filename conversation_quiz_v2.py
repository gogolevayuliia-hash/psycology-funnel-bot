def calculate_result_v2(answers: list[tuple[str, int]]) -> str:
    """
    Возвращает ключ результата из RESULTS_V2.
    answers: список (answer_type, score) по 9 вопросам.
    """
    scores = {"criticism": 0, "contempt": 0, "defense": 0, "wall": 0, "secure": 0}
    for atype, score in answers:
        if atype in scores:
            scores[atype] += score

    horsemen = ["criticism", "contempt", "defense", "wall"]
    max_horseman = max(scores[p] for p in horsemen)

    # Secure доминирует → НАДЁЖНЫЙ
    if scores["secure"] > max_horseman:
        return "secure"

    # Активные паттерны (порог ≥4)
    patterns = [(p, scores[p]) for p in horsemen if scores[p] >= 4]
    patterns.sort(key=lambda x: x[1], reverse=True)

    if not patterns:
        return "secure"

    if len(patterns) == 1:
        return patterns[0][0]

    # Два и более активных — берём двух лидеров
    p1, p2 = patterns[0][0], patterns[1][0]
    return _COMBO_CANONICAL.get(frozenset({p1, p2}), patterns[0][0])
